/**
 * THE WORLD — the face.
 *
 * A single-stroke letterform set in the Hershey simplex lineage: A-Z, a-z, 0-9 and
 * the punctuation press English actually needs, each character a set of polylines on
 * one fixed 100-unit cap grid — cap height at 0, x-height at 30, baseline at 100,
 * descender at 140. The renderer strokes these with round caps and joins; curves are
 * polygonal, as they were on the original plotters, and read as curves at 3x
 * supersampling.
 *
 * Nothing here draws. This module is data plus the two little constructors (P, ARC)
 * that keep the tables below readable; the geometry of the page never reaches it.
 */

export type Pt = [number, number];

export const CAP = 100;              // cap height in glyph units
export const XH = 30;                // x-height top
export const DESC = 140;             // descender bottom

export type Glyph = { w: number; s: Pt[][] };

/** "0,0 32,100" -> [[0,0],[32,100]] */
export const P = (s: string): Pt[] =>
  s.trim().split(/\s+/).map((t) => {
    const [a, b] = t.split(",");
    return [Number(a), Number(b)] as Pt;
  });

/**
 * Polyline arc: angles in degrees, 0 = right, 90 = down (y grows downward).
 * The sweep runs from a0 to a1, so a bowl that bulges to the RIGHT goes
 * 270 -> 450 (top, right, bottom) and one that bulges to the LEFT goes
 * 270 -> 90 (top, left, bottom). Full turns run 270 -> -90.
 */
export const ARC = (cx: number, cy: number, rx: number, ry: number,
                    a0: number, a1: number, n = 12): Pt[] => {
  const outv: Pt[] = [];
  for (let i = 0; i <= n; i++) {
    const a = ((a0 + (a1 - a0) * (i / n)) * Math.PI) / 180;
    outv.push([cx + rx * Math.cos(a), cy + ry * Math.sin(a)]);
  }
  return outv;
};

export const cat = (...parts: Pt[][]): Pt[] => parts.reduce((acc, p) => acc.concat(p), [] as Pt[]);

