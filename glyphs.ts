/** ink extents, used to keep serifs inside the letter's own width */
const BOX: Record<string, { x0: number; x1: number }> = {};

export function inkBox(ch: string) {
  let b = BOX[ch];
  if (b) return b;
  const g = GLYPH[ch];
  let x0 = 1e9, x1 = -1e9;
  if (g) for (const st of g.s) for (const pt of st) {
    if (pt[0] < x0) x0 = pt[0];
    if (pt[0] > x1) x1 = pt[0];
  }
  b = { x0, x1 };
  BOX[ch] = b;
  return b;
}
